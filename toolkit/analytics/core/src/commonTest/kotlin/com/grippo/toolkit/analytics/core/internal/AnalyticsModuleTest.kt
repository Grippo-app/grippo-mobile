class AnalyticsModuleTest {
    @Test fun qualifiedFeatureDefinitionsAreCollectedIntoTheSharedCatalog(): Unit = runTest {
        Dispatchers.setMain(StandardTestDispatcher(testScheduler))
        val first = object : AnalyticsEvent {
            override val schema = AnalyticsEventSchema("first_feature_event", 1, emptyList())
            override fun parameters() = emptyList<AnalyticsParameter>()
        }
        val second = object : AnalyticsEvent {
            override val schema = AnalyticsEventSchema("second_feature_event", 1, emptyList())
            override fun parameters() = emptyList<AnalyticsParameter>()
        }
        try {
            val application = koinApplication {
                modules(AnalyticsModule().module, module {
                    single { AnalyticsConfiguration(debug = true) }
                    // Test-only definitions exercise the qualifiers generated by @Named.
                    single(named("first_feature_analytics")) { AnalyticsSchema(listOf(first.schema)) }
                    single(named("second_feature_analytics")) { AnalyticsSchema(listOf(second.schema)) }
                })
            }
            try {
                val engine = application.koin.get<DefaultAnalytics>()
                try {
                    val sink = RecordingAnalyticsSink()
                    engine.attachSink(sink); engine.updateCollection(AnalyticsCollection.Granted)
                    engine.track(first); engine.track(second); runCurrent()
                    assertEquals(listOf("first_feature_event", "second_feature_event"), sink.payloads().map { it.name })
                } finally { engine.close() }
            } finally { application.close() }
        } finally { Dispatchers.resetMain() }
    }

    @Test fun moduleHonorsDebugAndReleaseConfiguration(): Unit = runTest {
        Dispatchers.setMain(StandardTestDispatcher(testScheduler))
        try {
            val event = object : AnalyticsEvent {
                override val schema = AnalyticsEventSchema("unregistered_test", 1, emptyList())
                override fun parameters() = emptyList<AnalyticsParameter>()
            }
            for (debug in listOf(true, false)) {
                val application = koinApplication {
                    modules(AnalyticsModule().module, module { single { AnalyticsConfiguration(debug = debug) } })
                }
                val engine = application.koin.get<DefaultAnalytics>()
                try {
                    engine.updateCollection(AnalyticsCollection.Granted)
                    if (debug) {
                        assertFailsWith<IllegalArgumentException> { engine.track(event) }
                        assertEquals(AnalyticsDisposition.InvalidEvent, engine.diagnostics().last().disposition)
                    } else {
                        engine.track(event)
                        assertEquals(emptyList(), engine.diagnostics())
                    }
                } finally {
                    engine.close()
                    application.close()
                }
            }
        } finally { Dispatchers.resetMain() }
    }

    @Test fun consumerAndBootstrapShareOneEngine(): Unit = runTest {
        Dispatchers.setMain(StandardTestDispatcher(testScheduler))
        try {
            val application = koinApplication {
                modules(AnalyticsModule().module, module { single { AnalyticsConfiguration(debug = false) } })
            }
            try {
                val engine = application.koin.get<DefaultAnalytics>()
                assertSame(engine, application.koin.get<Analytics>())
                assertSame(engine, application.koin.get<AnalyticsBootstrap>())
                engine.close()
            } finally { application.close() }
        } finally { Dispatchers.resetMain() }
    }
}
