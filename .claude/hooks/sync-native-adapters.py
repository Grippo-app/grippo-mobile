#!/usr/bin/env python3
"""Project native discovery projections. Canonical instructions remain in .claude."""
import argparse
import json
import os
from pathlib import Path
import runpy


def toml_string(value):
    # JSON quoting handles C0 controls; TOML also requires escaping DEL.
    return json.dumps(value, ensure_ascii=False).replace("\x7f", "\\u007f")


def expected_files(root, read_metadata=None):
    if read_metadata is None:
        read_metadata = runpy.run_path(str(root / ".claude/hooks/check-rulebook.py"))["frontmatter"]
    links, agents = {}, {}
    for skill in sorted((root / ".claude/skills").glob("*/SKILL.md")):
        if skill.is_file():
            name = skill.parent.name
            links[f".agents/skills/{name}"] = f"../../.claude/skills/{name}"
    for role in sorted((root / ".claude/agents").glob("*.md")):
        if not role.is_file():
            continue
        metadata = read_metadata(str(role)) or {}
        description = metadata.get("description")
        if not isinstance(description, str) or not description.strip():
            continue  # The canonical checker diagnoses invalid metadata.
        name = role.stem
        instruction = (
            f"Read CLAUDE.md and .claude/agents/{name}.md before work. "
            "That canonical role defines your rights, required skills, conditional references, "
            "duties and report. Follow the common launch contract in "
            ".claude/skills/task-orchestrator/references/agent-runtimes.md. "
            "Use the exact role guard mode before every shell command when native hooks "
            "are unavailable. Do not delegate. A tool's availability does not expand rights."
        )
        rows = ["# Generated by .claude/hooks/sync-native-adapters.py; edit the canonical role.",
                f"name = {toml_string(name)}",
                f"description = {toml_string(description)}",
                f"developer_instructions = {toml_string(instruction)}", "", "[features]",
                "memories = false", "request_permissions_tool = false"]
        if name not in {"runtime-verifier", "analytics-admin-auditor"}:
            rows += ["apps = false", "plugins = false"]
        agents[f".codex/agents/{name}.toml"] = "\n".join(rows) + "\n"
    return links, agents


def check(root, read_metadata=None):
    links, agents = expected_files(root, read_metadata)
    problems = []
    for relative in (".agents", ".agents/skills", ".codex", ".codex/agents"):
        path = root / relative
        if path.is_symlink() or (path.exists() and not path.is_dir()):
            problems.append(f"native container must be a regular directory: {relative}")
    for relative, target in links.items():
        path = root / relative
        canonical = root / ".claude/skills" / path.name
        if not path.is_symlink() or os.readlink(path) != target or not path.is_dir() or path.resolve() != canonical.resolve():
            problems.append(f"native skill projection must link to {target}: {relative}")
    for relative, source in agents.items():
        path = root / relative
        if not path.is_file() or path.is_symlink() or path.read_text() != source:
            problems.append(f"native agent adapter missing or drifted: {relative}")
    for base, expected in ((".agents/skills", links), (".codex/agents", agents)):
        directory = root / base
        if directory.is_dir():
            for path in directory.iterdir():
                if path.relative_to(root).as_posix() not in expected:
                    problems.append(f"unexpected native projection: {path.relative_to(root)}")
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Regenerate known project projections")
    args = parser.parse_args()
    root = Path.cwd()
    for relative in ("CLAUDE.md", ".claude/hooks/check-rulebook.py", ".claude/skills", ".claude/agents"):
        if not (root / relative).exists():
            parser.error(f"run from the repository root; missing {relative}")
    if args.write:
        links, agents = expected_files(root)
        for relative in (".agents", ".agents/skills", ".codex", ".codex/agents"):
            path = root / relative
            if path.is_symlink() or (path.exists() and not path.is_dir()):
                parser.error(f"refusing non-directory native container: {relative}")
        for relative in agents:
            path = root / relative
            if path.is_symlink() or (path.exists() and not path.is_file()):
                parser.error(f"refusing to replace a non-regular adapter: {relative}")
        for relative, target in links.items():
            path = root / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            if path.is_symlink():
                path.unlink()
            elif path.exists():
                parser.error(f"refusing to replace a non-symlink: {relative}")
            path.symlink_to(target, target_is_directory=True)
        for relative, source in agents.items():
            path = root / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(source, encoding="utf-8")
    problems = check(root)
    for problem in problems:
        print(problem)
    print(f"{len(problems)} native projection problem(s)")
    raise SystemExit(bool(problems))


if __name__ == "__main__":
    main()
