function normalizedKind(value) {
  return String(value || '').toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^_+|_+$/g, '');
}

export function knownEvidenceIssueCode(value) {
  return Object.prototype.hasOwnProperty.call(CODE_CATEGORY, normalizedKind(value));
}

export function evidenceIssueLabel(value) {
  var code = normalizedKind(value);
  if (!code) return i18n.t('board.figmaEvidence.issueKind.unknown');
  var exactKey = 'board.figmaEvidence.issueKind.' + code.toLowerCase();
  var exact = i18n.t(exactKey);
  if (exact !== exactKey) return exact;
  var category = CODE_CATEGORY[code] || 'unknown';
  return i18n.t('board.figmaEvidence.issueCategory.' + category);
}
